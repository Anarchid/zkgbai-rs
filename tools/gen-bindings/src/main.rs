//! Regenerates `crates/springai-sys/src/bindings.rs` from a Recoil source tree.
//!
//! Usage: `cargo run --manifest-path tools/gen-bindings/Cargo.toml -- <recoil-src> <out.rs>`

use std::path::PathBuf;

const WRAPPER: &str = r#"
#define VERSION_STRING "0.0.0"
#include "ExternalAI/Interface/SSkirmishAICallback.h"
#include "ExternalAI/Interface/SSkirmishAILibrary.h"
#include "ExternalAI/Interface/AISEvents.h"
#include "ExternalAI/Interface/AISCommands.h"
"#;

fn main() {
    let mut args = std::env::args().skip(1);
    let src = PathBuf::from(args.next().expect("usage: gen-bindings <recoil-src> <out.rs>"));
    let out = PathBuf::from(args.next().expect("usage: gen-bindings <recoil-src> <out.rs>"));
    let rts = src.join("rts");
    assert!(
        rts.join("ExternalAI/Interface/SSkirmishAICallback.h").exists(),
        "{} does not look like a Recoil source tree",
        src.display()
    );

    let bindings = bindgen::Builder::default()
        .header_contents("wrapper.h", WRAPPER)
        .clang_arg(format!("-I{}", rts.display()))
        .clang_arg(format!("-I{}", src.display()))
        .allowlist_type("SSkirmishAICallback")
        .allowlist_type("S[A-Za-z]+Event")
        .allowlist_type("S[A-Za-z]+Command")
        .allowlist_type("EventTopic")
        .allowlist_type("CommandTopic")
        .allowlist_type("UnitCommandOptions")
        .allowlist_var("COMMAND_.*")
        .allowlist_var("SKIRMISH_AI_PROPERTY_.*")
        .rustified_enum("EventTopic")
        .constified_enum_module("CommandTopic")
        .constified_enum_module("UnitCommandOptions")
        .derive_debug(false)
        .derive_default(true)
        .layout_tests(true)
        .generate_comments(false)
        .raw_line("// @generated by tools/gen-bindings from the Recoil engine AI interface headers.")
        .raw_line("// Do not edit by hand; regenerate with tools/regen-bindings.sh.")
        .generate()
        .expect("bindgen failed");

    bindings.write_to_file(&out).expect("failed to write bindings");
    eprintln!("wrote {}", out.display());
}
