//! The fight predictor: a port of the fitted `dps_stop` model
//! (tools/predictor/predict.py, zkgbai-runs/predictor/round2/SUMMARY.md).
//!
//! A fight is a [`FightSnapshot`]: the units of two sides with their current
//! health and positions. The model projects them onto the line between the
//! two sides' centroids and runs a deterministic one-dimensional a-move
//! fight in 0.1 s steps over a 90 s horizon: mobile units close until an
//! enemy is within their range, every weapon fires at its nearest target
//! in range as soon as it reloads, and each shot lands its expected damage
//! from fitted hit tables (per weapon, target def, range band and speed
//! band, with hierarchical shrinkage). A fitted disengagement hazard, read
//! at the end of every second, weights the running killed-cost fractions
//! into their expectation over the fight's stopping time. The "A withdraws
//! now" query is the same loop with every mobile A unit reversing at full
//! speed (the round-3 `q_withdraw` movement under the round-2 hazard).
//!
//! This module never touches the engine: unit and weapon stats arrive in
//! the snapshot (see `live.rs`), and the fitted tables are compiled in from
//! `crates/zkgbai/data/fightsim_*.tsv`, regenerated by
//! `tools/predictor/export_tables.py` (each file's first line says when and
//! from what it was fitted). [`worker`] runs it on its own thread.

pub mod live;
pub mod worker;

use std::collections::HashMap;
use std::sync::Arc;

const HITS_TSV: &str = include_str!("../../../data/fightsim_hits.tsv");
const DEFS_TSV: &str = include_str!("../../../data/fightsim_defs.tsv");
const COEF_TSV: &str = include_str!("../../../data/fightsim_coef.tsv");

/// Frames per simulation step.
const DT: i32 = 3;
/// Simulated frames at most (90 s).
const HORIZON: i32 = 2700;
/// Range bands: distance over range in fifths; band 5 is beyond range.
const RBANDS: i32 = 5;
/// Target speed band edges, elmos per frame.
const SPEED_EDGES: [f64; 3] = [0.5, 2.0, 4.0];
/// Shrinkage weight of each table level towards the level above.
const SHRINK: f64 = 20.0;
/// Hit rate prior where a weapon was never seen.
const PRIOR: f64 = 0.7;
/// Engine weapon classes whose shots leave no projectile: one rolled shot
/// is the whole salvo.
const HITSCAN: [&str; 3] = ["BeamLaser", "LightningCannon", "Rifle"];

/// One weapon of a unit type, as the fitted tables know it.
#[derive(Clone, Debug, PartialEq)]
pub struct WeaponSpec {
    /// Weapon def name (the hit tables' key).
    pub name: String,
    pub range: f32,
    /// Seconds.
    pub reload: f32,
    pub salvo: i32,
    /// Damage per projectile (default armor class).
    pub damage: f32,
    /// Engine weapon class (`"Cannon"`, `"BeamLaser"`, ...).
    pub weapon_type: String,
}

impl WeaponSpec {
    fn hitscan(&self) -> bool {
        HITSCAN.contains(&self.weapon_type.as_str())
    }
}

/// A unit type's stats for the simulation.
#[derive(Clone, Debug, PartialEq)]
pub struct UnitSpec {
    /// Unit def name (the hit tables' target key).
    pub def: String,
    /// Metal.
    pub cost: f32,
    /// Elmos per frame.
    pub speed: f32,
    pub mobile: bool,
    /// Weapons that do damage at range (no shields, fakes or no-weapons).
    pub weapons: Vec<WeaponSpec>,
}

/// A unit in a fight.
#[derive(Clone, Debug)]
pub struct SnapUnit {
    /// 0 = A (us), 1 = B.
    pub side: u8,
    pub spec: Arc<UnitSpec>,
    pub hp: f32,
    pub x: f32,
    pub z: f32,
}

/// The two sides of a prospective fight, as seen now.
#[derive(Clone, Debug, Default)]
pub struct FightSnapshot {
    pub units: Vec<SnapUnit>,
}

impl FightSnapshot {
    pub fn armed(&self, side: u8) -> usize {
        self.units.iter().filter(|u| u.side == side && !u.spec.weapons.is_empty()).count()
    }
}

/// What the model expects of a fight.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct FightOutcome {
    /// Expected killed share of each side's armed cost over the fight's
    /// stopping time (raw `dps_stop`).
    pub killed_a: f32,
    pub killed_b: f32,
    /// The same if every mobile A unit turns away now (`A withdraws`).
    pub withdraw_a: f32,
    pub withdraw_b: f32,
    /// Calibrated expected killed shares (zero-one-inflated Beta means).
    pub mean_a: f32,
    pub mean_b: f32,
    /// Calibrated P(A wins | decided), logistic on `killed_b - killed_a`.
    pub p_a_wins: f32,
    pub armed_a: u16,
    pub armed_b: u16,
}

// ----------------------------------------------------------------------------- hit tables

/// Target size classes the tables shrink through.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Cls {
    Small,
    Medium,
    Large,
    Static,
    Air,
}

impl Cls {
    fn parse(s: &str) -> Cls {
        match s {
            "small" => Cls::Small,
            "large" => Cls::Large,
            "static" => Cls::Static,
            "air" => Cls::Air,
            _ => Cls::Medium,
        }
    }
}

#[derive(Clone, Copy, Debug, Default)]
struct Cell {
    n: f64,
    hit_any: f64,
    hit_tgt: f64,
    dmg: f64,
    nominal: f64,
}

impl Cell {
    fn add(&mut self, o: &Cell) {
        self.n += o.n;
        self.hit_any += o.hit_any;
        self.hit_tgt += o.hit_tgt;
        self.dmg += o.dmg;
        self.nominal += o.nominal;
    }

    /// Hit rates (any unit, the target) shrunk towards `prior`.
    fn rate(&self, prior: f64) -> (f64, f64) {
        ((self.hit_any + SHRINK * prior) / (self.n + SHRINK), (self.hit_tgt + SHRINK * prior) / (self.n + SHRINK))
    }

    /// Damage landed per hit as a share of the nominal damage per shot.
    fn frac(&self) -> Option<f64> {
        (self.hit_any > 0.0 && self.nominal > 0.0 && self.n > 0.0)
            .then(|| self.dmg / self.hit_any / (self.nominal / self.n))
    }
}

/// Hit rate and damage per shot, by weapon and target.
pub struct HitTables {
    weapons: HashMap<String, u32>,
    tdefs: HashMap<String, u32>,
    cls: HashMap<String, Cls>,
    wd: Vec<Cell>,
    wd_cls: HashMap<(u32, Cls), Cell>,
    wd_tdef: HashMap<(u32, u32), Cell>,
    wd_tdef_rb: HashMap<(u32, u32, u8), Cell>,
    cells: HashMap<(u32, u32, u8, u8), Cell>,
}

/// A looked-up hit model entry.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Hit {
    /// P(a shot hits some unit) and P(it hits its target).
    pub p_any: f64,
    pub p_tgt: f64,
    /// Damage per hit as a share of the nominal damage per shot.
    pub frac: f64,
    /// Shots the weapon was seen firing in the training games.
    pub n: f64,
}

fn parse_f64(s: &str) -> Result<f64, String> {
    s.parse::<f64>().map_err(|e| format!("bad number {s:?}: {e}"))
}

fn data_lines(tsv: &str) -> impl Iterator<Item = &str> {
    tsv.lines().filter(|l| !l.is_empty() && !l.starts_with('#')).skip(1)
}

impl HitTables {
    fn load(hits: &str, defs: &str) -> Result<HitTables, String> {
        let mut cls = HashMap::new();
        for line in data_lines(defs) {
            let mut it = line.split('\t');
            let (Some(d), Some(c)) = (it.next(), it.next()) else { return Err(format!("defs: bad line {line:?}")) };
            cls.insert(d.to_owned(), Cls::parse(c));
        }
        let mut t = HitTables {
            weapons: HashMap::new(),
            tdefs: HashMap::new(),
            cls,
            wd: Vec::new(),
            wd_cls: HashMap::new(),
            wd_tdef: HashMap::new(),
            wd_tdef_rb: HashMap::new(),
            cells: HashMap::new(),
        };
        for line in data_lines(hits) {
            let f: Vec<&str> = line.split('\t').collect();
            if f.len() != 9 {
                return Err(format!("hits: bad line {line:?}"));
            }
            let nw = t.weapons.len() as u32;
            let w = *t.weapons.entry(f[0].to_owned()).or_insert(nw);
            if w as usize == t.wd.len() {
                t.wd.push(Cell::default());
            }
            let nt = t.tdefs.len() as u32;
            let d = *t.tdefs.entry(f[1].to_owned()).or_insert(nt);
            let rb = f[2].parse::<u8>().map_err(|e| format!("hits: {e}"))?;
            let sb = f[3].parse::<u8>().map_err(|e| format!("hits: {e}"))?;
            let cell = Cell {
                n: parse_f64(f[4])?,
                hit_any: parse_f64(f[5])?,
                hit_tgt: parse_f64(f[6])?,
                dmg: parse_f64(f[7])?,
                nominal: parse_f64(f[8])?,
            };
            let c = t.cls.get(f[1]).copied().unwrap_or(Cls::Medium);
            t.wd[w as usize].add(&cell);
            t.wd_cls.entry((w, c)).or_default().add(&cell);
            t.wd_tdef.entry((w, d)).or_default().add(&cell);
            t.wd_tdef_rb.entry((w, d, rb)).or_default().add(&cell);
            t.cells.entry((w, d, rb, sb)).or_default().add(&cell);
        }
        Ok(t)
    }

    /// Weapon key, if the weapon was ever seen.
    pub fn weapon(&self, name: &str) -> Option<u32> {
        self.weapons.get(name).copied()
    }

    /// Target key and size class of a unit def (an unknown def is a medium
    /// target the weapon tables know nothing about).
    pub fn target(&self, def: &str) -> (Option<u32>, Cls) {
        (self.tdefs.get(def).copied(), self.cls.get(def).copied().unwrap_or(Cls::Medium))
    }

    /// The fitted hit entry for a weapon against a target at a range band
    /// (fifths of range) and speed band, shrunk level by level from the
    /// weapon's overall rate: weapon, weapon x target class, x target def,
    /// x range band, x speed band.
    pub fn lookup(&self, w: Option<u32>, target: (Option<u32>, Cls), rb: u8, sb: u8) -> Hit {
        let mut hit = Hit { p_any: PRIOR, p_tgt: PRIOR, frac: 1.0, n: 0.0 };
        let Some(w) = w else { return hit };
        let row = &self.wd[w as usize];
        hit.n = row.n;
        (hit.p_any, hit.p_tgt) = row.rate(PRIOR);
        hit.frac = row.frac().filter(|f| *f != 0.0).unwrap_or(1.0);
        let (tdef, cls) = target;
        if let Some(row) = self.wd_cls.get(&(w, cls)) {
            (hit.p_any, hit.p_tgt) = row.rate(hit.p_any);
        }
        if let Some(d) = tdef
            && let Some(row) = self.wd_tdef.get(&(w, d))
        {
            (hit.p_any, hit.p_tgt) = row.rate(hit.p_any);
            if row.hit_any > 5.0 {
                hit.frac = row.frac().filter(|f| *f != 0.0).unwrap_or(hit.frac);
            }
            if let Some(row) = self.wd_tdef_rb.get(&(w, d, rb)) {
                (hit.p_any, hit.p_tgt) = row.rate(hit.p_any);
                if let Some(row) = self.cells.get(&(w, d, rb, sb)) {
                    (hit.p_any, hit.p_tgt) = row.rate(hit.p_any);
                }
            }
        }
        hit.p_any = hit.p_any.min(1.0);
        hit.p_tgt = hit.p_tgt.min(1.0);
        hit
    }
}

fn speed_band(spd: f64) -> u8 {
    SPEED_EDGES.iter().filter(|e| spd >= **e).count() as u8
}

fn expit(x: f64) -> f64 {
    1.0 / (1.0 + (-x).exp())
}

fn logit(p: f64) -> f64 {
    let p = p.clamp(0.005, 0.995);
    (p / (1.0 - p)).ln()
}

// ----------------------------------------------------------------------------- coefficients

/// The disengagement hazard: P(the fight ends this second without a wipe),
/// logistic on the elapsed time, the killed shares and the cost ratio.
#[derive(Clone, Debug, PartialEq)]
pub struct Hazard {
    /// const, log1p(t), t/10, max(kA, kB), min(kA, kB), |kA - kB|,
    /// log(costA / costB).
    pub w: [f64; 7],
}

impl Hazard {
    pub fn h(&self, t: f64, ka: f64, kb: f64, logratio: f64) -> f64 {
        let f = [1.0, (1.0 + t).ln(), t / 10.0, ka.max(kb), ka.min(kb), (ka - kb).abs(), logratio];
        expit(f.iter().zip(&self.w).map(|(a, b)| a * b).sum())
    }
}

/// Zero-one-inflated Beta calibration of a killed share on the logit of
/// the raw prediction (its mean is all the port needs).
#[derive(Clone, Debug, PartialEq)]
pub struct ZoiBeta {
    pub theta: [f64; 7],
}

impl ZoiBeta {
    pub fn mean(&self, raw: f64) -> f64 {
        let z = logit(raw);
        let t = &self.theta;
        let p0 = expit(t[0] + t[1] * z);
        let p1 = expit(t[2] + t[3] * z);
        let mu = expit(t[4] + t[5] * z).clamp(1e-4, 1.0 - 1e-4);
        (1.0 - p0) * (p1 + (1.0 - p1) * mu)
    }
}

/// The fitted model.
pub struct Model {
    pub hits: HitTables,
    pub hazard: Hazard,
    /// P(A wins) = expit(w0 + w1 (killed_b - killed_a)).
    pub win: [f64; 2],
    pub cal_a: ZoiBeta,
    pub cal_b: ZoiBeta,
    /// The data files' fitting headers.
    pub fitted: String,
}

fn take<const N: usize>(coef: &[(String, f64)], prefix: &str) -> Result<[f64; N], String> {
    let v: Vec<f64> = coef.iter().filter(|(k, _)| k.starts_with(prefix)).map(|(_, v)| *v).collect();
    v.try_into().map_err(|v: Vec<f64>| format!("coef: {prefix}* has {} values, not {N}", v.len()))
}

impl Model {
    /// The compiled-in tables.
    pub fn load() -> Result<Model, String> {
        Model::parse(HITS_TSV, DEFS_TSV, COEF_TSV)
    }

    fn parse(hits: &str, defs: &str, coef_tsv: &str) -> Result<Model, String> {
        let hits = HitTables::load(hits, defs)?;
        let mut coef = Vec::new();
        for line in data_lines(coef_tsv) {
            let mut it = line.split('\t');
            let (Some(k), Some(v)) = (it.next(), it.next()) else { return Err(format!("coef: bad line {line:?}")) };
            coef.push((k.to_owned(), parse_f64(v)?));
        }
        let fitted = [HITS_TSV, COEF_TSV]
            .iter()
            .filter_map(|t| t.lines().next())
            .map(|l| l.trim_start_matches('#').trim().to_owned())
            .collect::<Vec<_>>()
            .join("; ");
        Ok(Model {
            hits,
            hazard: Hazard { w: take(&coef, "hazard.")? },
            win: take(&coef, "win.")?,
            cal_a: ZoiBeta { theta: take(&coef, "zoibA.")? },
            cal_b: ZoiBeta { theta: take(&coef, "zoibB.")? },
            fitted,
        })
    }

    /// Run the fitted model on a snapshot: the a-move fight and the
    /// withdrawal query, both under the disengagement hazard.
    pub fn predict(&self, snap: &FightSnapshot) -> FightOutcome {
        let units = self.sim_units(snap);
        let (ka, kb) = simulate(&units, &self.hits, Some(&self.hazard), false);
        let (wa, wb) = simulate(&units, &self.hits, Some(&self.hazard), true);
        FightOutcome {
            killed_a: ka as f32,
            killed_b: kb as f32,
            withdraw_a: wa as f32,
            withdraw_b: wb as f32,
            mean_a: self.cal_a.mean(ka) as f32,
            mean_b: self.cal_b.mean(kb) as f32,
            p_a_wins: expit(self.win[0] + self.win[1] * (kb - ka)) as f32,
            armed_a: snap.armed(0) as u16,
            armed_b: snap.armed(1) as u16,
        }
    }

    /// The snapshot's units on the fight's line, with table keys resolved.
    fn sim_units(&self, snap: &FightSnapshot) -> Vec<SimUnit> {
        let xs = project(snap);
        snap.units
            .iter()
            .zip(xs)
            .map(|(u, x)| {
                let weapons: Vec<SimWeapon> = u
                    .spec
                    .weapons
                    .iter()
                    .map(|w| {
                        let salvo = w.salvo.max(1);
                        let hitscan = w.hitscan();
                        SimWeapon {
                            key: self.hits.weapon(&w.name),
                            range: w.range as f64,
                            reload: ((w.reload as f64 * 30.0).round_ties_even() as i32).max(1),
                            hitscan,
                            salvo,
                            nominal: if hitscan { w.damage as f64 * salvo as f64 } else { w.damage as f64 },
                            next: 0,
                        }
                    })
                    .collect();
                SimUnit {
                    side: u.side,
                    target: self.hits.target(&u.spec.def),
                    hp: u.hp as f64,
                    cost: u.spec.cost as f64,
                    armed: !weapons.is_empty(),
                    mobile: u.spec.mobile,
                    speed: u.spec.speed as f64,
                    x,
                    max_range: weapons.iter().map(|w| w.range).fold(0.0, f64::max),
                    weapons,
                    alive: true,
                    moving: false,
                }
            })
            .collect()
    }
}

// ----------------------------------------------------------------------------- simulation

#[derive(Clone, Debug)]
struct SimWeapon {
    key: Option<u32>,
    range: f64,
    /// Frames.
    reload: i32,
    hitscan: bool,
    salvo: i32,
    /// Damage of one rolled shot: the salvo for hitscan, one projectile
    /// otherwise.
    nominal: f64,
    next: i32,
}

#[derive(Clone, Debug)]
struct SimUnit {
    side: u8,
    target: (Option<u32>, Cls),
    hp: f64,
    cost: f64,
    armed: bool,
    mobile: bool,
    speed: f64,
    x: f64,
    weapons: Vec<SimWeapon>,
    max_range: f64,
    alive: bool,
    moving: bool,
}

/// Positions along the axis from A's centroid to B's (A's centroid at 0).
fn project(snap: &FightSnapshot) -> Vec<f64> {
    let cent = |side: u8| {
        let pts: Vec<(f64, f64)> =
            snap.units.iter().filter(|u| u.side == side).map(|u| (u.x as f64, u.z as f64)).collect();
        (!pts.is_empty()).then(|| {
            let n = pts.len() as f64;
            (pts.iter().map(|p| p.0).sum::<f64>() / n, pts.iter().map(|p| p.1).sum::<f64>() / n)
        })
    };
    let (Some(ca), Some(cb)) = (cent(0), cent(1)) else {
        return snap.units.iter().map(|u| if u.side == 0 { 0.0 } else { 400.0 }).collect();
    };
    let d0 = ((cb.0 - ca.0).powi(2) + (cb.1 - ca.1).powi(2)).sqrt();
    if d0 < 1.0 {
        return snap.units.iter().map(|u| if u.side == 0 { 0.0 } else { d0 }).collect();
    }
    let (ax, az) = ((cb.0 - ca.0) / d0, (cb.1 - ca.1) / d0);
    snap.units.iter().map(|u| (u.x as f64 - ca.0) * ax + (u.z as f64 - ca.1) * az).collect()
}

/// The deterministic one-dimensional fight (predict.py `simulate` with
/// `rng=None`): expected killed share of each side's armed cost, weighted
/// over the stopping time when a hazard is given. `withdraw`: every mobile
/// A unit turns away from B at full speed instead of fighting.
fn simulate(template: &[SimUnit], hits: &HitTables, hazard: Option<&Hazard>, withdraw: bool) -> (f64, f64) {
    let mut us: Vec<SimUnit> = template.to_vec();
    let cost0 = [0u8, 1].map(|s| us.iter().filter(|u| u.side == s && u.armed).map(|u| u.cost).sum::<f64>());
    let mut killed = [0.0f64; 2];
    let kfrac = |killed: &[f64; 2]| [0, 1].map(|s| if cost0[s] > 0.0 { killed[s] / cost0[s] } else { 0.0 });
    let lr = (cost0[0].max(1.0) / cost0[1].max(1.0)).ln();
    let mut surv = 1.0;
    let mut exp_k = [0.0f64; 2];
    let mut quiet = 0;
    let mut f = 0;
    while f < HORIZON {
        if let Some(hz) = hazard
            && f > 0
            && f % 30 == 0
        {
            let k = kfrac(&killed);
            let h = hz.h((f / 30 - 1) as f64, k[0], k[1], lr);
            exp_k[0] += surv * h * k[0];
            exp_k[1] += surv * h * k[1];
            surv *= 1.0 - h;
        }
        let has_armed = [0u8, 1].map(|s| us.iter().any(|u| u.alive && u.armed && u.side == s));
        if !has_armed[0] || !has_armed[1] {
            break;
        }
        // Movement: close until an enemy is within own range (or, withdrawing,
        // back away), towards the nearest enemy where it stands now (units
        // earlier in order have moved already, as in the Python model).
        let mut moved = false;
        for i in 0..us.len() {
            if !us[i].alive {
                continue;
            }
            us[i].moving = false;
            if !us[i].mobile || us[i].speed <= 0.0 {
                continue;
            }
            let (side, ux) = (us[i].side, us[i].x);
            let nearest = us
                .iter()
                .filter(|e| e.alive && e.side != side)
                .map(|e| e.x)
                .min_by(|a, b| (a - ux).abs().total_cmp(&(b - ux).abs()));
            let Some(nearest) = nearest else { continue };
            let u = &mut us[i];
            let dist = (nearest - u.x).abs();
            if withdraw && u.side == 0 {
                u.x -= if nearest > u.x { u.speed * DT as f64 } else { -u.speed * DT as f64 };
                u.moving = true;
                moved = true;
                continue;
            }
            if !u.armed {
                continue;
            }
            if dist > u.max_range * 0.95 {
                let step = (u.speed * DT as f64).min(dist - u.max_range * 0.9);
                u.x += if nearest > u.x { step } else { -step };
                u.moving = true;
                moved = true;
            }
        }
        // Fire: every reloaded weapon at its nearest living target in
        // range, damage applied at once (a kill removes the target for the
        // weapons and units after it in order). The nearest living enemy is
        // the target of every weapon that reaches it, so it is found once
        // per unit and again only after a kill.
        let mut shot_fired = false;
        for i in 0..us.len() {
            if !us[i].alive || !us[i].armed {
                continue;
            }
            let (side, ux) = (us[i].side, us[i].x);
            let nearest = |us: &[SimUnit]| {
                let mut best: Option<(f64, usize)> = None;
                for (j, e) in us.iter().enumerate() {
                    if e.alive && e.side != side {
                        let d = (e.x - ux).abs();
                        if best.is_none_or(|(bd, _)| d < bd) {
                            best = Some((d, j));
                        }
                    }
                }
                best
            };
            let mut target = nearest(&us);
            for wi in 0..us[i].weapons.len() {
                if f < us[i].weapons[wi].next {
                    continue;
                }
                let range = us[i].weapons[wi].range;
                let Some((dist, j)) = target.filter(|(d, _)| *d <= range) else { continue };
                us[i].weapons[wi].next = f + us[i].weapons[wi].reload;
                shot_fired = true;
                let rb = if range > 0.0 { ((RBANDS as f64 * dist / range) as i32).min(RBANDS) } else { RBANDS } as u8;
                let sb = speed_band(if us[j].moving { us[j].speed } else { 0.0 });
                let (key, hitscan, salvo, nominal) = {
                    let w = &us[i].weapons[wi];
                    (w.key, w.hitscan, w.salvo, w.nominal)
                };
                let hit = hits.lookup(key, us[j].target, rb, sb);
                let shots = if hitscan { 1 } else { salvo };
                let dmg = hit.p_tgt * hit.frac * nominal * shots as f64;
                if dmg > 0.0 {
                    let t = &mut us[j];
                    t.hp -= dmg;
                    if t.hp <= 0.0 {
                        t.alive = false;
                        if t.armed {
                            killed[t.side as usize] += t.cost;
                        }
                        target = nearest(&us);
                    }
                }
            }
        }
        quiet = if shot_fired || (moved && !withdraw) { 0 } else { quiet + DT };
        if quiet > if withdraw { 150 } else { 300 } {
            break;
        }
        f += DT;
    }
    let k = kfrac(&killed);
    if hazard.is_some() { (exp_k[0] + surv * k[0], exp_k[1] + surv * k[1]) } else { (k[0], k[1]) }
}

